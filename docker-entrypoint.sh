#!/usr/bin/env sh
# Entrypoint for the Kenn Forge container (formerly middleman).
#
# kenn-forge binds a LOOPBACK address by design (it validates that host is
# loopback and refuses 0.0.0.0). To make it reachable from outside the
# container we run it on 127.0.0.1:${MIDDLEMAN_INTERNAL_PORT} and bridge
# 0.0.0.0:${MIDDLEMAN_PORT} -> that loopback port with socat (the same pattern
# the project's dev compose uses).
#
# The settings keep their MIDDLEMAN_* names: deployments built against the
# middleman image set them, and forge itself reads none of them. This script
# is the only place they are translated. KENN_FORGE_HOME is the one forge
# needs; without it forge ignores the seeded config and starts empty under
# $HOME/.kenn/forge.
#
# On first run we seed a minimal config under MIDDLEMAN_HOME. An existing
# config is left untouched (edit it and restart to customize: repos, providers,
# allowed_hosts, etc.).
set -eu

: "${MIDDLEMAN_HOME:=/data}"
: "${MIDDLEMAN_PORT:=8091}"            # external port (socat listener; published)
: "${MIDDLEMAN_INTERNAL_PORT:=8092}"  # loopback port middleman binds
CONFIG="${MIDDLEMAN_HOME}/config.toml"
# forge resolves its config, and finds a middleman.db to migrate, from here.
export KENN_FORGE_HOME="${MIDDLEMAN_HOME}"

# Strip quotes/backslashes/newlines so a value cannot break the generated TOML.
toml_safe() { printf '%s' "$1" | tr -d '"\\\n\r'; }

mkdir -p "${MIDDLEMAN_HOME}"

if [ ! -f "${CONFIG}" ]; then
  echo "middleman: seeding default config at ${CONFIG} (loopback :${MIDDLEMAN_INTERNAL_PORT})" >&2
  {
    echo '# Generated by docker-entrypoint.sh on first run.'
    echo '# Edit this file and restart the container to customize.'
    echo '# Keep host = "127.0.0.1": the socat bridge dials 127.0.0.1, so another'
    echo '# loopback form (e.g. [::1]) would start but be unreachable.'
    echo 'sync_interval = "5m"'
    echo 'github_token_env = "MIDDLEMAN_GITHUB_TOKEN"'
    echo 'host = "127.0.0.1"'
    echo "port = ${MIDDLEMAN_INTERNAL_PORT}"
    echo "data_dir = \"${MIDDLEMAN_HOME}\""
    # Requests arrive via socat with the original Host header, so the Host must be
    # allow-listed. Always allow the in-container healthcheck (loopback at the
    # external port); append operator-supplied MIDDLEMAN_ALLOWED_HOSTS (comma-
    # separated) for Tailscale/reverse-proxy domain access.
    allowed="\"127.0.0.1:${MIDDLEMAN_PORT}\", \"localhost:${MIDDLEMAN_PORT}\""
    if [ -n "${MIDDLEMAN_ALLOWED_HOSTS:-}" ]; then
      # Strip quotes/backslashes/newlines so a stray value cannot break the
      # generated TOML. Values must be bare host[:port] tokens.
      extra="$(printf '%s' "${MIDDLEMAN_ALLOWED_HOSTS}" \
        | tr -d '"\\\n\r' \
        | awk -v RS=, '{gsub(/^[ \t]+|[ \t]+$/,""); if($0!="") printf ", \""$0"\""}')"
      allowed="${allowed}${extra}"
    fi
    echo "allowed_hosts = [${allowed}]"
    # Only enable when actually behind a reverse proxy that sets X-Forwarded-Host:
    # with it on, kenn-forge REQUIRES a forwarded-host header on every request
    # (direct access and the healthcheck would otherwise be rejected).
    case "${MIDDLEMAN_TRUST_REVERSE_PROXY:-}" in
      1|true|TRUE|yes) echo 'trust_reverse_proxy = true' ;;
    esac
    # Optional URL sub-path so a reverse proxy (e.g. Kenn Console) can front
    # kenn-forge under a prefix behind one login. Empty leaves the default "/".
    # Top-level key: emit before any table below.
    if [ -n "${MIDDLEMAN_BASE_PATH:-}" ]; then
      echo "base_path = \"$(toml_safe "${MIDDLEMAN_BASE_PATH}")\""
    fi
    # Front door -> roborev proxy target (table must follow the top-level keys).
    if [ -n "${MIDDLEMAN_ROBOREV_ENDPOINT:-}" ]; then
      echo ''
      echo '[roborev]'
      echo "endpoint = \"$(toml_safe "${MIDDLEMAN_ROBOREV_ENDPOINT}")\""
    fi
  } > "${CONFIG}"
fi

# Front door -> kata proxy: kenn-forge discovers daemons from $KATA_HOME/config.toml.
# Seed a catalog pointing at the in-network kata when MIDDLEMAN_KATA_URL is set.
if [ -n "${MIDDLEMAN_KATA_URL:-}" ]; then
  : "${KATA_HOME:=${MIDDLEMAN_HOME}/kata}"
  export KATA_HOME
  mkdir -p "${KATA_HOME}"
  [ -n "${KATA_AUTH_TOKEN:-}" ] || echo "middleman: warning: MIDDLEMAN_KATA_URL set but KATA_AUTH_TOKEN is empty; kata proxy will fail auth" >&2
  KATA_CATALOG="${KATA_HOME}/config.toml"
  if [ ! -f "${KATA_CATALOG}" ]; then
    echo "middleman: seeding kata catalog at ${KATA_CATALOG} -> ${MIDDLEMAN_KATA_URL}" >&2
    {
      echo 'active_daemon = "kenn-stack"'
      echo '[[daemon]]'
      echo 'name = "kenn-stack"'
      echo "url = \"$(toml_safe "${MIDDLEMAN_KATA_URL}")\""
      echo 'token_env = "KATA_AUTH_TOKEN"'
      echo 'allow_insecure = true'
    } > "${KATA_CATALOG}"
  fi
fi

# forge's first start renames middleman.db to forge.db in data_dir, and nothing
# renames it back: the old image would then start on an empty database. Keep a
# copy to roll back to, once, while the database is still closed. data_dir is
# MIDDLEMAN_HOME in the config seeded above.
if [ -f "${MIDDLEMAN_HOME}/middleman.db" ] && [ ! -e "${MIDDLEMAN_HOME}/forge.db" ] \
   && ! ls "${MIDDLEMAN_HOME}"/middleman.db.pre-forge.* >/dev/null 2>&1; then
  backup="${MIDDLEMAN_HOME}/middleman.db.pre-forge.$(date -u +%Y%m%dT%H%M%SZ)"
  for suffix in "" -wal -shm; do
    if [ -f "${MIDDLEMAN_HOME}/middleman.db${suffix}" ]; then
      cp -p "${MIDDLEMAN_HOME}/middleman.db${suffix}" "${backup}${suffix}"
    fi
  done
  echo "kenn-forge: kept the middleman database as ${backup} before its one-way migration" >&2
fi

# Seed-only mode: write the config and exit (used by tests to validate the
# generated config without starting the server). No kenn-forge binary required.
if [ "${MIDDLEMAN_SEED_ONLY:-}" = "1" ]; then
  exit 0
fi

# Honor a hand-edited config: read the port kenn-forge will actually bind,
# from the config serve will use. A --config passed to the container is handed
# to serve below, so it is the one to read when present.
serve_config="${CONFIG}"
prev=""
for arg in "$@"; do
  case "${prev}" in --config|-config) serve_config="${arg}" ;; esac
  case "${arg}" in --config=*|-config=*) serve_config="${arg#*=}" ;; esac
  prev="${arg}"
done
backend_port="$(kenn-forge config read --config "${serve_config}" port 2>/dev/null || true)"
case "${backend_port}" in
  ''|*[!0-9]*) backend_port="${MIDDLEMAN_INTERNAL_PORT}" ;;
esac

# The trap goes in before anything starts, and stops only kenn-forge: the
# bridge stays up while it drains, and is stopped once it has exited. A
# signal that arrives before kenn-forge has started is passed on as soon as
# it has.
mm_pid="" socat_pid="" stopping=""
terminate() {
  stopping=1
  if [ -n "${mm_pid}" ]; then kill -TERM "${mm_pid}" 2>/dev/null || true; fi
}
trap terminate INT TERM

socat "TCP-LISTEN:${MIDDLEMAN_PORT},fork,bind=0.0.0.0,reuseaddr" "TCP:127.0.0.1:${backend_port}" &
socat_pid=$!

# KENN_FORGE_HOME makes the default config path resolve to ${CONFIG}. On the
# first start against a middleman volume, forge renames middleman.db to
# forge.db in data_dir; the copy kept above is the way back.
kenn-forge serve "$@" &
mm_pid=$!
if [ -n "${stopping}" ]; then kill -TERM "${mm_pid}" 2>/dev/null || true; fi

# Disable errexit around wait so a non-zero kenn-forge exit still runs cleanup.
# A trapped TERM makes wait return at once, while kenn-forge is still shutting
# down; this script is PID 1, and leaving now would have the kernel kill it
# mid-shutdown. So wait again until it has really exited.
set +e
wait "${mm_pid}"
status=$?
while kill -0 "${mm_pid}" 2>/dev/null; do
  wait "${mm_pid}"
  status=$?
done
set -e
kill -TERM "${socat_pid}" 2>/dev/null || true
wait "${socat_pid}" 2>/dev/null || true
exit "${status}"
